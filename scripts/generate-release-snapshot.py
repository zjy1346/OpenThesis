"""Create a deterministic, compressed manifest of Windows release build inputs."""

from __future__ import annotations

import argparse
import gzip
import hashlib
import json
import os
from pathlib import Path
import stat
import subprocess


TREES = ("src", "desktop", "build_support", "scripts", ".build-tools", ".cargo")
ROOT_FILES = {"README.md", "LICENSE"}
ROOT_SUFFIXES = {".py", ".spec", ".toml", ".txt", ".json", ".lock", ".yml", ".yaml"}
GENERATED_BUILD_INFO_PATHS = (
    "src/openthesis/resources/build-info.json",
    "desktop/src-tauri/resources/build-info.json",
)
EXCLUDED = (
    "desktop/dist",
    "desktop/src-tauri/target",
    "desktop/src-tauri/gen",
    "desktop/src-tauri/resources/bin",
    "desktop/node_modules/.vite",
    "desktop/node_modules/.cache",
    # Generated immediately before compilation from version, commit and build
    # time; development placeholders are not package inputs.
    *GENERATED_BUILD_INFO_PATHS,
)


def included(name: str) -> bool:
    path = Path(name)
    parts = path.parts
    selected = (
        bool(parts)
        and (
            parts[0] in TREES
            or name in ROOT_FILES
            or (len(parts) == 1 and path.suffix in ROOT_SUFFIXES)
        )
    )
    return selected and not (
        "__pycache__" in parts
        or ".git" in parts
        or name.endswith((".pyc", ".pyo"))
        or any(name == prefix or name.startswith(prefix + "/") for prefix in EXCLUDED)
    )


def entry(path: Path, name: str) -> dict[str, object]:
    info = path.lstat()
    link = path.is_symlink()
    return {
        "path": name,
        "type": "symlink" if link else "file",
        "mode": oct(stat.S_IMODE(info.st_mode)),
        "symlink_target": os.readlink(path) if link else None,
        "bytes": info.st_size,
        "sha256": hashlib.file_digest(path.open("rb"), "sha256").hexdigest(),
    }


def tracked_deletions(root: Path) -> list[dict[str, object]]:
    raw_entries = subprocess.check_output(
        ["git", "ls-files", "-s", "-z"], cwd=root
    ).split(b"\0")
    rows: list[dict[str, object]] = []
    for raw in raw_entries:
        if not raw:
            continue
        metadata, encoded_name = raw.split(b"\t", 1)
        mode = metadata.decode("ascii").split()[0]
        name = encoded_name.decode("utf-8")
        if included(name) and not (root / name).exists():
            rows.append({
                "path": name,
                "type": "deleted",
                "mode": mode,
                "symlink_target": None,
                "bytes": 0,
                "sha256": None,
            })
    return rows


def generated_build_info_entries(
    source: Path, *, version: str, base_commit: str,
) -> list[dict[str, object]]:
    """Account for actual generated bytes consumed by both package builds.

    Package creation restores development placeholders. Use its materialized
    sidecar resource instead, never hash a placeholder as the compiled input.
    The package builder writes these same bytes to both source destinations.
    """
    payload = source.read_bytes()
    identity = json.loads(payload.decode("utf-8"))
    if not isinstance(identity, dict):
        raise ValueError("generated build identity must be an object")
    if identity.get("version") != version or identity.get("commit") != base_commit:
        raise ValueError("generated build identity does not match this snapshot")
    values = [identity.get(key) for key in
              ("version", "commit", "build_time_utc", "contract_version")]
    if any(not isinstance(value, str) or not value for value in values):
        raise ValueError("generated build identity has incomplete fields")
    expected = hashlib.sha256("|".join(values).encode("utf-8")).hexdigest()
    if identity.get("build_id") != expected:
        raise ValueError("generated build identity digest is invalid")
    result = []
    for name in GENERATED_BUILD_INFO_PATHS:
        result.append({
            "path": name,
            "type": "file",
            "mode": oct(stat.S_IMODE(source.stat().st_mode)),
            "symlink_target": None,
            "bytes": len(payload),
            "sha256": hashlib.sha256(payload).hexdigest(),
            "generated": True,
            "generation_rule": "scripts/package-desktop.ps1: shared UTF-8 buildInfo",
            "build_id": expected,
        })
    return result


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("version")
    parser.add_argument("workflow")
    parser.add_argument("--generated-build-info", type=Path,
                        help="Materialized package build-info.json, not a development placeholder")
    args = parser.parse_args()
    root = Path.cwd().resolve()
    base_commit = subprocess.check_output(
        ["git", "rev-parse", "HEAD"], cwd=root, text=True,
    ).strip()
    rows: list[dict[str, object]] = []
    for path in sorted(root.iterdir(), key=lambda item: item.name):
        if path.is_file() and included(path.name):
            rows.append(entry(path, path.name))
    for tree in TREES:
        base = root / tree
        if not base.exists():
            continue
        for current, dirs, files in os.walk(base):
            current_path = Path(current)
            dirs[:] = sorted(
                directory
                for directory in dirs
                if included((current_path / directory).relative_to(root).as_posix())
            )
            for filename in sorted(files):
                path = current_path / filename
                relative = path.relative_to(root).as_posix()
                if included(relative):
                    rows.append(entry(path, relative))
    rows.extend(tracked_deletions(root))
    if args.generated_build_info is not None:
        rows.extend(generated_build_info_entries(
            args.generated_build_info, version=args.version, base_commit=base_commit,
        ))
    rows.sort(key=lambda row: str(row["path"]))
    target = root / "docs" / "releases" / f"{args.workflow}-{args.version}-inputs.jsonl.gz"
    target.parent.mkdir(parents=True, exist_ok=True)
    with target.open("wb") as raw_target:
        with gzip.GzipFile(filename="", mode="wb", fileobj=raw_target, mtime=0) as archive:
            for row in rows:
                archive.write(
                    (json.dumps(row, sort_keys=True, ensure_ascii=False) + "\n").encode("utf-8")
                )
    result = {
        "manifest": str(target),
        "entries": len(rows),
        "sha256": hashlib.file_digest(target.open("rb"), "sha256").hexdigest(),
        "base": base_commit,
        "trees": TREES,
        "root_files": sorted(ROOT_FILES),
        "root_suffixes": sorted(ROOT_SUFFIXES),
        "exclusions": EXCLUDED,
        "generated_build_info_included": args.generated_build_info is not None,
    }
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
